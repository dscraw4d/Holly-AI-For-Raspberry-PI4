#define N 32u
typedef uint64_t number[N];
typedef __uint128_t wide;
static void load(number a,const uint8_t p[256]){
 for(unsigned i=0;i<N;i++){
  a[i]=0;for(unsigned j=0;j<8;j++)a[i]=(a[i]<<8)|p[248u-8u*i+j];
 }
}
static void save(const number a,uint8_t p[256]){
 for(unsigned i=0;i<N;i++)for(unsigned j=0;j<8;j++)p[255-8*i-j]=(uint8_t)(a[i]>>(8*j));
}
static uint64_t subtract(number d,const number a,const number b){
 wide borrow=0;
 for(unsigned i=0;i<N;i++){
  wide v=(wide)b[i]+borrow;d[i]=(uint64_t)((wide)a[i]-v);borrow=(wide)a[i]<v;
 }
 return (uint64_t)borrow;
}
static void reduce(number a,const number n,uint64_t high){
 number d;uint64_t borrow=subtract(d,a,n),mask=0u-(uint64_t)((high!=0)|(borrow==0));
 for(unsigned i=0;i<N;i++)a[i]=(a[i]&~mask)|(d[i]&mask);
 holly_secret_wipe(d,sizeof(d));
}
static void twice(number a,const number n){
 uint64_t carry=0;
 for(unsigned i=0;i<N;i++){uint64_t next=a[i]>>63;a[i]=(a[i]<<1)|carry;carry=next;}
 reduce(a,n,carry);
}
static void product(number out,const number a,const number b,const number n,uint64_t inverse){
 uint64_t t[2*N+1]={0};
 for(unsigned i=0;i<N;i++){
  wide carry=0;
  for(unsigned j=0;j<N;j++){
   wide v=(wide)a[i]*b[j]+t[i+j]+carry;t[i+j]=(uint64_t)v;carry=v>>64;
  }
  t[i+N]=(uint64_t)carry;
 }
 for(unsigned i=0;i<N;i++){
  uint64_t m=t[i]*inverse;wide carry=0;
  for(unsigned j=0;j<N;j++){
   wide v=(wide)m*n[j]+t[i+j]+carry;t[i+j]=(uint64_t)v;carry=v>>64;
  }
  for(unsigned j=i+N;j<=2*N;j++){
   wide v=(wide)t[j]+carry;t[j]=(uint64_t)v;carry=v>>64;
  }
 }
 for(unsigned i=0;i<N;i++)out[i]=t[N+i];
 reduce(out,n,t[2*N]);holly_secret_wipe(t,sizeof(t));
}
int holly_modexp2048(const uint8_t b[256],const uint8_t *e,size_t bytes,const uint8_t m[256],uint8_t out[256]){
 if(!b||!e||!bytes||bytes>256||!m||!out||!(m[0]&128u)||!(m[255]&1u))return -1;
 number n,a,rr={0},one={0},r,s,t,table[16];
 load(n,m);load(a,b);
 if(!subtract(t,a,n)){holly_secret_wipe(a,sizeof(a));return -1;}
 uint64_t inv=1;for(unsigned i=0;i<6;i++)inv*=2u-n[0]*inv;inv=0u-inv;
 rr[0]=1;one[0]=1;
 for(unsigned i=0;i<4096;i++)twice(rr,n);
 product(a,a,rr,n,inv);product(r,one,rr,n,inv);
 for(unsigned j=0;j<N;j++){table[0][j]=r[j];table[1][j]=a[j];}
 for(unsigned i=2;i<16;i++)product(table[i],table[i-1],a,n,inv);
 /* Fixed four-bit windows. Scan every table entry for each window rather
  * than indexing memory with secret exponent bits. Same product schedule
  * for all exponents of the same public byte length. */
 for(size_t i=0;i<bytes;i++)for(unsigned half=0;half<2;half++){
  for(unsigned k=0;k<4;k++)product(r,r,r,n,inv);
  unsigned nibble=(e[i]>>(half?0:4))&15u;
  for(unsigned j=0;j<N;j++)t[j]=0;
  for(unsigned digit=0;digit<16;digit++){
   uint64_t mask=0u-(uint64_t)(digit==nibble);
   for(unsigned j=0;j<N;j++)t[j]|=table[digit][j]&mask;
  }
  product(s,r,t,n,inv);for(unsigned j=0;j<N;j++)r[j]=s[j];
 }
 product(s,r,one,n,inv);save(s,out);
 holly_secret_wipe(a,sizeof(a));holly_secret_wipe(r,sizeof(r));holly_secret_wipe(s,sizeof(s));
 holly_secret_wipe(t,sizeof(t));holly_secret_wipe(table,sizeof(table));
 return 0;
}
